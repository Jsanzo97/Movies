package jsanzo.movies.data.model

import jsanzo.movies.domain.model.DomainMovieDetails

data class DataMovieDetails(
    val adult: Boolean,
    val backdropPath: String,
    val belongsToCollection: DataMovieCollection?,
    val budget: Int,
    val genres: List<DataMovieGenre>,
    val homepage: String,
    val id: Int,
    val imdbId: String,
    val originCountry: List<String>,
    val originalLanguage: String,
    val originalTitle: String,
    val overview: String,
    val popularity: Double,
    val posterPath: String,
    val productionCompanies: List<DataMovieProductionCompany>,
    val productionCountries: List<DataMovieProductionCountry>,
    val releaseDate: String,
    val revenue: Long,
    val runtime: Int,
    val spokenLanguages: List<DataMovieSpokenLanguage>,
    val status: String,
    val tagline: String,
    val title: String,
    val video: Boolean,
    val voteAverage: Double,
    val voteCount: Int,
)

fun DataMovieDetails.toMovieDetails() = DomainMovieDetails(
    adult = adult,
    backdropPath = backdropPath,
    belongsToCollection = belongsToCollection?.toMovieCollection(),
    budget = budget,
    genres = genres.map { it.toMovieGenre() },
    homepage = homepage,
    id = id,
    imdbId = imdbId,
    originCountry = originCountry,
    originalLanguage = originalLanguage,
    originalTitle = originalTitle,
    overview = overview,
    popularity = popularity,
    posterPath = posterPath,
    productionCompanies = productionCompanies.map { it.toMovieProductionCompany() },
    productionCountries = productionCountries.map { it.toMovieProductionCountry() },
    releaseDate = releaseDate,
    revenue = revenue,
    runtime = runtime,
    spokenLanguages = spokenLanguages.map { it.toMovieSpokenLanguage() },
    status = status,
    tagline = tagline,
    title = title,
    video = video,
    voteAverage = voteAverage,
    voteCount = voteCount,
)
