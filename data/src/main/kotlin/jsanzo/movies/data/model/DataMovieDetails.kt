package jsanzo.movies.data.model

import jsanzo.movies.domain.model.DomainMovieDetails

data class DataMovieDetails(
    val adult: Boolean,
    val backdropPath: String?,
    val belongsToCollection: DataMovieCollection?,
    val budget: Int,
    val genres: List<DataMovieGenre>,
    val homepage: String?,
    val id: Int,
    val imdbId: String?,
    val originCountry: List<String>,
    val originalLanguage: String,
    val originalTitle: String,
    val overview: String?,
    val popularity: Double,
    val posterPath: String?,
    val productionCompanies: List<DataMovieProductionCompany>,
    val productionCountries: List<DataMovieProductionCountry>,
    val releaseDate: String,
    val revenue: Long,
    val runtime: Int?,
    val spokenLanguages: List<DataMovieSpokenLanguage>,
    val status: String,
    val tagline: String?,
    val title: String,
    val video: Boolean,
    val voteAverage: Double,
    val voteCount: Int,
)

fun DataMovieDetails.toMovieDetails() = DomainMovieDetails(
    adult,
    backdropPath,
    belongsToCollection?.toMovieCollection(),
    budget,
    genres.map { it.toMovieGenre() },
    homepage,
    id,
    imdbId,
    originCountry,
    originalLanguage,
    originalTitle,
    overview,
    popularity,
    posterPath,
    productionCompanies.map { it.toMovieProductionCompany() },
    productionCountries.map { it.toMovieProductionCountry() },
    releaseDate,
    revenue,
    runtime,
    spokenLanguages.map { it.toMovieSpokenLanguage() },
    status,
    tagline,
    title,
    video,
    voteAverage,
    voteCount,
)
